import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const endpoint=process.env.CLOUD_TEST_URL||'http://127.0.0.1:8787';
if(!/^http:\/\/(127\.0\.0\.1|localhost):/.test(endpoint))throw Error('Local test only');
const config=JSON.parse(await readFile(new URL('../content/scenario.json',import.meta.url),'utf8'));
const headers={'Content-Type':'application/json'};
const call=(path,method='GET',data,auth=true)=>fetch(endpoint+path,{method,headers:auth?headers:{},body:data?JSON.stringify(data):undefined});
assert.equal((await call('/access').then(r=>r.json())).publicEditing,true);
assert.equal((await call('/draft','GET',null,false)).status,200);
assert.equal((await fetch(endpoint+'/draft',{headers:{...headers,Origin:'https://evil.example'}})).status,403);
const before=await (await call('/draft')).json();
assert.equal((await call('/draft','PUT',{revision:before.revision,config:{}})).status,400);
const saved=await (await call('/draft','PUT',{revision:before.revision,config})).json();assert.equal(saved.revision,before.revision+1);
assert.equal((await call('/draft','PUT',{revision:before.revision,config})).status,409);
assert.equal((await call('/publish','POST',{revision:saved.revision})).status,400);
assert.equal((await call('/publish','POST',{revision:before.revision,confirmPublish:true})).status,409);
assert.equal((await call('/publish','POST',{revision:saved.revision,confirmPublish:true,title:'長'.repeat(81)})).status,400);
assert.equal((await call('/publish','POST',{revision:saved.revision,confirmPublish:true,title:123})).status,400);
assert.equal((await call('/publish','POST',{revision:saved.revision,confirmPublish:true,title:'  第3章の会話を追加  '})).status,200);
const history=await (await call('/history')).json();assert.equal(history.find(h=>h.revision===saved.revision).title,'第3章の会話を追加');
const published=await (await call('/public','GET',null,false)).json();assert.deepEqual(published.config,config);
const changed=structuredClone(config);changed.contacts[0].name='共有テスト';
const race=await Promise.all([call('/draft','PUT',{revision:saved.revision,config:changed}),call('/draft','PUT',{revision:saved.revision,config})]);assert.deepEqual(race.map(r=>r.status).sort(),[200,409]);
assert.deepEqual((await (await call('/public','GET',null,false)).json()).config,config);
assert.deepEqual((await (await call('/history/'+saved.revision)).json()).config,config);
console.log('PASS: anonymous editing, explicit publish confirmation, CORS, validation, draft/public separation, concurrent conflict, history');
